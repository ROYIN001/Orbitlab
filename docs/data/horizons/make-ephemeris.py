#!/usr/bin/env python3
"""Turn the JPL Horizons tables here (DE441, geocentric, ICRF, km and km/s, hourly TDB)
into src/data/ephemeris-1969.ts, for Apollo 11's week (roadmap C01, docs/PHYSICS.md §13.10).

    python3 docs/data/horizons/make-ephemeris.py

The tables were fetched from https://ssd.jpl.nasa.gov/api/horizons.api with
COMMAND='301' (the Moon) and '10' (the Sun), CENTER='500@399', EPHEM_TYPE='VECTORS',
VEC_TABLE='2', REF_SYSTEM='ICRF', REF_PLANE='FRAME', OUT_UNITS='KM-S', TIME_TYPE='TDB',
CSV_FORMAT='YES', STEP_SIZE='60 min'.

Each value is kept as it always was — positions to the metre, velocities to a tenth of a
millimetre a second — but written as an integer (m, 1e-7 km/s), each column of the table
as its fourth differences in time after its first four values: the same numbers, a fifth
of the text. `unpack` in the generated file sums them back and divides, which gives each
value exactly the double its decimal would (the quotient of two integers is rounded once).
"""
import os
from datetime import datetime
from decimal import Decimal
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(os.path.dirname(here)))
ORDER = 4
SCALES = (1000, 1000, 1000, 10 ** 7, 10 ** 7, 10 ** 7)

def rows(name):
    text = open(os.path.join(here, name)).read()
    body = text.split('$$SOE')[1].split('$$EOE')[0]
    out = []
    for line in body.strip().splitlines():
        parts = [p.strip() for p in line.split(',')]
        jd = float(parts[0]); vals = [float(x) for x in parts[2:8]]
        out.append((jd, vals, parts[1]))
    return out

def tdb(date):
    # 'A.D. 1969-Jul-16 13:00:00.0000' -> '1969-07-16 13:00'
    return datetime.strptime(date[5:22], '%Y-%b-%d %H:%M').strftime('%Y-%m-%d %H:%M')

# the span the header states, the same for both bodies
spans = {(r[0][2], r[-1][2]) for r in (rows('moon-1969-07-icrf.txt'), rows('sun-1969-07-icrf.txt'))}
assert len(spans) == 1
(first, last), = spans

def packed(name):
    r = rows(name)
    jd0, step = r[0][0], round((r[1][0] - r[0][0]) * 24, 6)
    cols = []
    for c in range(6):
        # the value as the table always rounded it, then exactly as an integer of its unit
        digits = 3 if c < 3 else 7
        exact = [Decimal(repr(round(v[c], digits))) * SCALES[c] for _, v, _ in r]
        assert all(x == x.to_integral_value() for x in exact)
        col = [int(x) for x in exact]
        heads = []
        for _ in range(ORDER):
            heads.append(col[0])
            col = [col[i] - col[i - 1] for i in range(1, len(col))]
        cols.append(heads + col)
    return jd0, step, len(r), cols

out = ['/**',
       f' * The Moon and the Sun, geocentric, from JPL Horizons (DE441), hourly from {tdb(first)} to',
       f' * {tdb(last)} TDB: position (km) and velocity (km/s) in the ICRF, six numbers a row.',
       ' * Generated by docs/data/horizons/make-ephemeris.py from the tables beside it; do not edit.',
       ' * Each column is packed as integers (m, 1e-7 km/s): its first four values, then its fourth',
       ' * differences in time.',
       ' */',
       '',
       'export interface EphemerisTable { jd0: number; stepHours: number; count: number; data: readonly number[] }',
       '',
       f'/** The table from its packed columns: each summed back {ORDER} times, then in km and km/s, row by row. */',
       'function unpack(jd0: number, stepHours: number, count: number, cols: readonly (readonly number[])[]): EphemerisTable {',
       '  const data: number[] = new Array(count * 6);',
       '  cols.forEach((packed, c) => {',
       f'    let x = packed.slice({ORDER});',
       f'    for (let k = {ORDER} - 1; k >= 0; k--) {{',
       '      const y = [packed[k]];',
       '      for (const d of x) y.push(y[y.length - 1] + d);',
       '      x = y;',
       '    }',
       '    for (let i = 0; i < count; i++) data[i * 6 + c] = x[i] / (c < 3 ? 1000 : 1e7);',
       '  });',
       '  return { jd0, stepHours, count, data };',
       '}',
       '']
for key, name in (('MOON', 'moon-1969-07-icrf.txt'), ('SUN', 'sun-1969-07-icrf.txt')):
    jd0, step, n, cols = packed(name)
    out.append(f'export const {key}_1969 = unpack({jd0}, {step}, {n}, [')
    for col in cols:
        out.append('  [' + ','.join(str(x) for x in col) + '],')
    out.append(']);')
    out.append('')
open(os.path.join(root, 'src', 'data', 'ephemeris-1969.ts'), 'w').write('\n'.join(out))
print('written')
