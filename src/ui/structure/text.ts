/** The copies loaded so far: Thai always; English and Russian once `loadLanguage` has fetched them. */
const loaded: Partial<Record<Lang, Copy>> = { th };

/** Fetch a language's copy if it is not here yet (Thai always is). Resolves either way: a copy that cannot be had falls back to Thai. */
export async function loadLanguage(lang: Lang): Promise<void> {
  if (loaded[lang]) return;
  try {
    loaded[lang] = lang === 'en' ? (await import('./structure-en')).copy : (await import('./structure-ru')).copy;
  } catch { /* offline before the copy was ever fetched: the source language shows meanwhile */ }
}

/** The section has words for `key` (in Thai, the source: the other two carry the same keys). */
export const hasText = (key: string): boolean => Object.hasOwn(th, key);

/** A language's copy is here (the section then shows it; else it shows the Thai while it is fetched). */
export const hasLanguage = (lang: Lang): boolean => !!loaded[lang];

/** The section's text in the interface language, {param}s filled in; Thai, then the key, where a language lacks one. */
export function tx(key: string, params?: Record<string, string | number>, lang: Lang = getLang()): string {
  let s = loaded[lang]?.[key] ?? th[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** A number in the interface language's way (Thai and English: 1,234.5; Russian: 1 234,5). */
export function num(value: number, digits = 2, lang: Lang = getLang()): string {
  const locale = lang === 'ru' ? 'ru-RU' : lang === 'th' ? 'th-TH-u-nu-latn' : 'en-GB';
  return value.toLocaleString(locale, { minimumFractionDigits: digits, maximumFractionDigits: digits });
}
